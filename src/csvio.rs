//! CSV/TSV export and import in WizTree's format.

use crate::format::{self, from_win_attrs, win_attrs};
use crate::model::{Node, NodeId, Tree, flags, NONE};
use std::collections::HashMap;
use std::io::{self, BufRead, BufWriter, Write};
use std::path::Path;

pub const APP_NAME: &str = "WizTree";
pub const APP_VERSION: &str = env!("CARGO_PKG_VERSION");

#[derive(Clone, Debug)]
pub struct ExportOptions {
    pub dates: bool,
    pub folder_sizes: bool,
    pub split_names: bool,
    pub drive_size: bool,
    pub percent_of_parent: bool,
    pub max_depth: u32,
    pub file_ids: bool,
    pub files: bool,
    pub folders: bool,
    pub utc: bool,
    pub tsv: bool,
    /// 0 = by size, 1 = by name, 2 = by modified.
    pub sort_by: u8,
    /// Limit the number of exported rows (0 = unlimited).
    pub limit: usize,
}

impl Default for ExportOptions {
    fn default() -> Self {
        ExportOptions {
            dates: false,
            folder_sizes: false,
            split_names: false,
            drive_size: true,
            percent_of_parent: false,
            max_depth: 0,
            file_ids: false,
            files: true,
            folders: true,
            utc: false,
            tsv: false,
            sort_by: 0,
            limit: 0,
        }
    }
}

fn quote(s: &str, delim: char) -> String {
    if s.contains(delim) || s.contains('"') || s.contains('\n') || s.contains(',') {
        format!("\"{}\"", s.replace('"', "\"\""))
    } else {
        s.to_string()
    }
}

pub fn generated_line() -> String {
    format!(
        "Generated by {} {} {}",
        APP_NAME,
        APP_VERSION,
        chrono::Local::now().format("%Y/%m/%d %H:%M:%S")
    )
}

/// Export rows for `ids` (a tree traversal is performed for folders when
/// `recursive` is set; otherwise exactly the given list is written).
pub fn export(
    tree: &Tree,
    ids: &[NodeId],
    recursive: bool,
    o: &ExportOptions,
    path: &Path,
    donation_line: Option<&str>,
) -> io::Result<usize> {
    let f = std::fs::File::create(path)?;
    let mut w = BufWriter::with_capacity(1 << 20, f);
    let d = if o.tsv { '\t' } else { ',' };
    let ds = d.to_string();
    writeln!(w, "{}{}", generated_line(), donation_line.map(|s| format!(" ({s})")).unwrap_or_default())?;
    // Column order recovered from WizTreeMac's ScanEngine.headerLine.
    let mut hdr: Vec<&str> = vec!["File Name", "Size", "Allocated", "Modified", "Attributes", "Files", "Folders"];
    if o.file_ids {
        hdr.extend(if cfg!(windows) { ["MFTRECNO", "MFTPARENTRECNO"] } else { ["FILEID", "PARENTFILEID"] });
    }
    if o.dates {
        hdr.extend(["LASTACCESSDATE", "CREATEDDATE"]);
    }
    if o.folder_sizes {
        hdr.extend(["FOLDERSIZE", "FOLDERALLOCATED"]);
    }
    if o.split_names {
        hdr.extend(["ROOT", "FOLDERNAME", "FILENAME", "FILEEXT"]);
    }
    if o.percent_of_parent {
        hdr.push("PERCENTOFPARENT");
    }
    if o.drive_size {
        hdr.extend(["DRIVECAPACITY", "FREESPACE", "USEDSPACE", "RESERVEDSPACE"]);
    }
    writeln!(w, "{}", hdr.join(&ds))?;

    let date = |t: i64| if o.utc { format::date_utc(t) } else { format::date(t) };
    let mut count = 0usize;
    let mut stack: Vec<(NodeId, u32)> = ids.iter().rev().map(|&i| (i, 0)).collect();
    let sep = tree.path_sep;
    while let Some((id, depth)) = stack.pop() {
        if o.limit > 0 && count >= o.limit {
            break;
        }
        let n = &tree.nodes[id as usize];
        if n.is_deleted() {
            continue;
        }
        let is_dir = n.is_dir();
        if (is_dir && o.folders) || (!is_dir && o.files) {
            let mut p = tree.path(id);
            if is_dir && !p.ends_with(sep) && !p.ends_with('/') {
                p.push(sep);
            }
            // WizTree writes extensionless file names with a trailing dot
            // ("README."); import strips exactly one again.
            let nm = tree.name(id);
            if !is_dir && !tree.is_root(id) && (!nm.contains('.') || nm.ends_with('.')) {
                p.push('.');
            }
            let mut row: Vec<String> = vec![
                quote(&p, d),
                n.size.to_string(),
                n.alloc.to_string(),
                date(n.mtime),
                // Like WizTree: folders carry their NTFS attributes, which
                // never include the directory bit.
                (win_attrs(n.flags) & if is_dir { !0x10 } else { !0 }).to_string(),
                if is_dir { n.files.to_string() } else { "0".into() },
                if is_dir { n.folders.to_string() } else { "0".into() },
            ];
            if o.file_ids {
                row.push(n.file_id.to_string());
                let pid = if n.parent != NONE && !tree.is_root(id) { tree.nodes[n.parent as usize].file_id } else { 0 };
                row.push(pid.to_string());
            }
            if o.dates {
                row.push(date(n.atime));
                row.push(date(n.ctime));
            }
            if o.folder_sizes {
                if is_dir {
                    let (mut s, mut a) = (0u64, 0u64);
                    for &k in tree.kids(id) {
                        let kn = &tree.nodes[k as usize];
                        if !kn.is_dir() {
                            s += kn.size;
                            a += kn.alloc;
                        }
                    }
                    row.push(s.to_string());
                    row.push(a.to_string());
                } else {
                    row.push(String::new());
                    row.push(String::new());
                }
            }
            if o.split_names {
                let chain = tree.chain(id);
                let root = tree.name(chain[0]).to_string();
                let folder = if is_dir {
                    p.clone()
                } else if chain.len() > 1 {
                    let mut f = tree.path(chain[chain.len() - 2]);
                    if !f.ends_with(sep) && !f.ends_with('/') {
                        f.push(sep);
                    }
                    f
                } else {
                    root.clone()
                };
                let name = if is_dir { String::new() } else { tree.name(id).to_string() };
                let ext = if is_dir { String::new() } else { tree.exts.names[n.ext as usize].clone() };
                row.push(quote(&root, d));
                row.push(quote(&folder, d));
                row.push(quote(&name, d));
                row.push(quote(&ext, d));
            }
            if o.percent_of_parent {
                let pct = if n.parent != NONE && !tree.is_root(id) {
                    let ps = tree.nodes[n.parent as usize].size;
                    if ps > 0 { n.size as f64 / ps as f64 * 100.0 } else { 0.0 }
                } else {
                    100.0
                };
                row.push(format!("{pct:.1}"));
            }
            if o.drive_size {
                if tree.is_root(id) {
                    let v = &tree.volume;
                    row.extend([v.total.to_string(), v.free.to_string(), v.used().to_string(), v.reserved.to_string()]);
                } else {
                    row.extend([String::new(), String::new(), String::new(), String::new()]);
                }
            }
            writeln!(w, "{}", row.join(&ds))?;
            count += 1;
        }
        if recursive && is_dir && (o.max_depth == 0 || depth + 1 < o.max_depth) {
            let mut kids: Vec<NodeId> = tree.kids(id).to_vec();
            match o.sort_by {
                1 => kids.sort_by(|a, b| tree.name(*a).to_lowercase().cmp(&tree.name(*b).to_lowercase())),
                2 => kids.sort_by(|a, b| tree.nodes[*b as usize].mtime.cmp(&tree.nodes[*a as usize].mtime)),
                _ => {}
            }
            for &k in kids.iter().rev() {
                stack.push((k, depth + 1));
            }
        }
    }
    w.flush()?;
    Ok(count)
}

pub fn export_file_types(tree: &Tree, path: &Path, tsv: bool, sort_by: u8) -> io::Result<()> {
    let mut w = BufWriter::new(std::fs::File::create(path)?);
    let d = if tsv { "\t" } else { "," };
    writeln!(w, "{}", generated_line())?;
    writeln!(w, "{}", ["Extension", "File Type", "Percent", "Size", "Allocated", "Files"].join(d))?;
    let total = tree.total_size().max(1);
    let mut stats = tree.ext_stats.clone();
    match sort_by {
        1 => stats.sort_by(|a, b| tree.exts.names[a.ext as usize].cmp(&tree.exts.names[b.ext as usize])),
        2 => stats.sort_by(|a, b| b.files.cmp(&a.files)),
        3 => stats.sort_by(|a, b| b.alloc.cmp(&a.alloc)),
        _ => {}
    }
    for s in &stats {
        let e = &tree.exts.names[s.ext as usize];
        let ext = if e.is_empty() { "(No Extension)".to_string() } else { format!(".{e}") };
        let desc = crate::filetypes::describe(e);
        writeln!(
            w,
            "{}{d}{}{d}{:.1}{d}{}{d}{}{d}{}",
            quote(&ext, d.chars().next().unwrap()),
            quote(&desc, d.chars().next().unwrap()),
            s.size as f64 / total as f64 * 100.0,
            s.size,
            s.alloc,
            s.files
        )?;
    }
    w.flush()
}

fn split_csv_line(line: &str, delim: char) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let mut inq = false;
    let mut chars = line.chars().peekable();
    while let Some(c) = chars.next() {
        if inq {
            if c == '"' {
                if chars.peek() == Some(&'"') {
                    cur.push('"');
                    chars.next();
                } else {
                    inq = false;
                }
            } else {
                cur.push(c);
            }
        } else if c == '"' {
            inq = true;
        } else if c == delim {
            out.push(std::mem::take(&mut cur));
        } else {
            cur.push(c);
        }
    }
    out.push(cur);
    out
}

/// Import a WizTree CSV (or TSV) export back into a tree.
pub fn import(path: &Path, progress: Option<&crate::scan::Progress>) -> io::Result<Tree> {
    let f = std::fs::File::open(path)?;
    let mut rd = io::BufReader::with_capacity(1 << 20, f);
    let mut tree = Tree::new();
    let mut line = String::new();
    let mut header: Option<Vec<String>> = None;
    let mut delim = ',';
    let mut dir_map: HashMap<String, NodeId> = HashMap::new();
    let mut leaf_sizes: HashMap<NodeId, (u64, u64, u32)> = HashMap::new();
    let mut col: HashMap<String, usize> = HashMap::new();
    loop {
        line.clear();
        if rd.read_line(&mut line)? == 0 {
            break;
        }
        let l = line.trim_end_matches(['\r', '\n']).trim_start_matches('\u{feff}');
        if l.is_empty() {
            continue;
        }
        if header.is_none() {
            if l.starts_with("Generated by") {
                continue;
            }
            if l.starts_with("File Name") || l.starts_with("\"File Name") {
                delim = if l.contains('\t') { '\t' } else { ',' };
                let h = split_csv_line(l, delim);
                for (i, n) in h.iter().enumerate() {
                    let n = match n.trim() {
                        "MFTRECNO" | "FILEID" => "File ID",
                        "MFTPARENTRECNO" | "PARENTFILEID" => "Parent File ID",
                        "LASTACCESSDATE" => "Last Accessed",
                        "CREATEDDATE" => "Created",
                        other => other,
                    };
                    col.entry(n.to_string()).or_insert(i);
                }
                header = Some(h);
                continue;
            }
            return Err(io::Error::new(io::ErrorKind::InvalidData, "Failed to import CSV file"));
        }
        let fields = split_csv_line(l, delim);
        let get = |name: &str| col.get(name).and_then(|&i| fields.get(i)).map(|s| s.as_str()).unwrap_or("");
        let full = get("File Name");
        if full.is_empty() {
            continue;
        }
        if tree.volume.total == 0 {
            if let Ok(v) = get("DRIVECAPACITY").trim().parse::<u64>() {
                tree.volume.total = v;
                tree.volume.free = get("FREESPACE").trim().parse().unwrap_or(0);
                tree.volume.reserved = get("RESERVEDSPACE").trim().parse().unwrap_or(0);
            }
        }
        let is_dir = full.ends_with('\\') || full.ends_with('/');
        if tree.roots.is_empty() || (is_dir && !dir_map.contains_key(full.trim_end_matches(['\\', '/']))) && find_parent(&dir_map, full).is_none() {
            // A new root.
            let sep = if full.contains('\\') { '\\' } else { '/' };
            tree.path_sep = sep;
            let name = if is_dir { full.to_string() } else { full.to_string() };
            let mut rn = name.trim_end_matches(['\\', '/']).to_string();
            if rn.is_empty() || rn.ends_with(':') {
                rn = name.clone();
            }
            let node = Node {
                flags: flags::DIR | flags::ROOT | from_win_attrs(get("Attributes").parse().unwrap_or(0)),
                mtime: format::parse_date(get("Modified")),
                ..Default::default()
            };
            let id = tree.add_node(NONE, &rn, node);
            tree.roots.push(id);
            dir_map.insert(full.trim_end_matches(['\\', '/']).to_string(), id);
            leaf_sizes.insert(id, (get("Size").parse().unwrap_or(0), get("Allocated").parse().unwrap_or(0), get("Files").parse().unwrap_or(0)));
            continue;
        }
        let trimmed = full.trim_end_matches(['\\', '/']);
        let Some((parent_path, name)) = trimmed.rsplit_once(['\\', '/']) else { continue };
        let name = if is_dir { name } else { name.strip_suffix('.').unwrap_or(name) };
        let parent = match dir_map.get(parent_path) {
            Some(&p) => p,
            None => match dir_map.get(&format!("{parent_path}{}", tree.path_sep)) {
                Some(&p) => p,
                None => ensure_dirs(&mut tree, &mut dir_map, parent_path),
            },
        };
        let size: u64 = get("Size").parse().unwrap_or(0);
        let alloc: u64 = get("Allocated").parse().unwrap_or(0);
        let mut fl = from_win_attrs(get("Attributes").parse().unwrap_or(0));
        if is_dir {
            fl |= flags::DIR;
        } else {
            fl &= !flags::DIR;
        }
        let node = Node {
            size,
            alloc,
            flags: fl,
            mtime: format::parse_date(get("Modified")),
            atime: format::parse_date(get("Last Accessed")),
            ctime: format::parse_date(get("Created")),
            file_id: get("File ID").parse().unwrap_or(0),
            ..Default::default()
        };
        let id = tree.add_node(parent, name, node);
        if is_dir {
            dir_map.insert(trimmed.to_string(), id);
            leaf_sizes.insert(id, (size, alloc, get("Files").parse().unwrap_or(0)));
        }
        if let Some(p) = progress {
            if is_dir {
                p.folders.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
            } else {
                p.files.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                p.bytes.fetch_add(size, std::sync::atomic::Ordering::Relaxed);
            }
            if p.cancelled() {
                break;
            }
        }
    }
    if header.is_none() {
        return Err(io::Error::new(io::ErrorKind::InvalidData, "Failed to import CSV file"));
    }
    // Folders exported without their files: keep their stated size via a synthetic child.
    let mut has_child = vec![false; tree.nodes.len()];
    for n in &tree.nodes {
        if n.parent != NONE {
            has_child[n.parent as usize] = true;
        }
    }
    let mut add: Vec<(NodeId, u64, u64)> = Vec::new();
    for (&id, &(s, a, _)) in &leaf_sizes {
        if !has_child[id as usize] && s > 0 {
            add.push((id, s, a));
        }
    }
    for (id, s, a) in add {
        tree.add_node(id, "[files]", Node { size: s, alloc: a, flags: flags::SYNTHETIC, ..Default::default() });
    }
    tree.finalize();
    Ok(tree)
}

fn find_parent(map: &HashMap<String, NodeId>, full: &str) -> Option<NodeId> {
    let t = full.trim_end_matches(['\\', '/']);
    let (p, _) = t.rsplit_once(['\\', '/'])?;
    map.get(p).copied().or_else(|| map.get(&format!("{p}\\")).copied()).or_else(|| map.get(&format!("{p}/")).copied())
}

fn ensure_dirs(tree: &mut Tree, map: &mut HashMap<String, NodeId>, path: &str) -> NodeId {
    if let Some(&id) = map.get(path) {
        return id;
    }
    match path.rsplit_once(['\\', '/']) {
        Some((pp, name)) if !pp.is_empty() => {
            let parent = ensure_dirs(tree, map, pp);
            let id = tree.add_node(parent, name, Node { flags: flags::DIR, ..Default::default() });
            map.insert(path.to_string(), id);
            id
        }
        _ => {
            let id = tree.add_node(NONE, path, Node { flags: flags::DIR | flags::ROOT, ..Default::default() });
            tree.roots.push(id);
            map.insert(path.to_string(), id);
            id
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn roundtrip() {
        let mut t = Tree::new();
        t.path_sep = '/';
        let r = t.add_node(NONE, "/data", Node { flags: flags::DIR | flags::ROOT, ..Default::default() });
        t.roots.push(r);
        let a = t.add_node(r, "a, b", Node { flags: flags::DIR, ..Default::default() });
        t.add_node(a, "x.txt", Node { size: 100, alloc: 4096, mtime: 1_700_000_000, ..Default::default() });
        t.add_node(r, "z.bin", Node { size: 5, alloc: 4096, ..Default::default() });
        t.add_node(r, "README", Node { size: 7, ..Default::default() });
        t.add_node(r, "odd.", Node { size: 9, ..Default::default() });
        t.add_node(r, ".gitignore", Node { size: 0, ..Default::default() });
        t.finalize();
        let p = std::env::temp_dir().join(format!("wt_rt_{}.csv", std::process::id()));
        let n = export(&t, &t.roots.clone(), true, &ExportOptions { dates: true, split_names: true, ..Default::default() }, &p, None).unwrap();
        assert_eq!(n, 7);
        let t2 = import(&p, None).unwrap();
        assert_eq!(t2.total_size(), 121);
        assert_eq!(t2.nodes[t2.roots[0] as usize].files, 5);
        assert!(t2.find_path("/data/a, b/x.txt").is_some());
        assert!(t2.find_path("/data/README").is_some(), "extensionless name round-trips");
        assert!(t2.find_path("/data/odd.").is_some(), "trailing-dot name round-trips");
        assert!(t2.find_path("/data/.gitignore").is_some(), "dot-file round-trips");
        assert_eq!(t2.nodes[t2.find_path("/data/a, b/x.txt").unwrap() as usize].mtime, 1_700_000_000);
        let _ = std::fs::remove_file(p);
    }
}
