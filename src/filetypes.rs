//! Human readable file type descriptions (the "File Type" column).

pub fn describe(ext: &str) -> String {
    if ext.is_empty() {
        return "File".to_string();
    }
    let known = match ext {
        "txt" | "text" => "Text Document",
        "log" => "Log File",
        "md" => "Markdown Document",
        "pdf" => "PDF Document",
        "doc" | "docx" => "Microsoft Word Document",
        "xls" | "xlsx" => "Microsoft Excel Worksheet",
        "ppt" | "pptx" => "Microsoft PowerPoint Presentation",
        "odt" => "OpenDocument Text",
        "ods" => "OpenDocument Spreadsheet",
        "odp" => "OpenDocument Presentation",
        "rtf" => "Rich Text Format",
        "csv" => "Comma Separated Values File",
        "tsv" => "Tab Separated Values File",
        "json" => "JSON File",
        "xml" => "XML Document",
        "yaml" | "yml" => "YAML File",
        "toml" => "TOML File",
        "ini" | "cfg" | "conf" => "Configuration Settings",
        "html" | "htm" => "HTML Document",
        "css" => "Cascading Style Sheet",
        "js" | "mjs" | "cjs" => "JavaScript File",
        "ts" => "TypeScript File",
        "py" => "Python Source File",
        "rs" => "Rust Source File",
        "c" => "C Source File",
        "h" => "C Header File",
        "cpp" | "cc" | "cxx" => "C++ Source File",
        "hpp" => "C++ Header File",
        "java" => "Java Source File",
        "class" => "Java Class File",
        "jar" => "Java Archive",
        "go" => "Go Source File",
        "sh" | "bash" | "zsh" => "Shell Script",
        "bat" | "cmd" => "Windows Batch File",
        "ps1" => "PowerShell Script",
        "exe" => "Application",
        "dll" => "Application Extension",
        "sys" => "System File",
        "msi" => "Windows Installer Package",
        "so" => "Shared Library",
        "dylib" => "Dynamic Library",
        "a" | "lib" => "Static Library",
        "o" | "obj" => "Object File",
        "app" => "Application Bundle",
        "deb" => "Debian Package",
        "rpm" => "RPM Package",
        "appimage" => "AppImage Application",
        "flatpak" => "Flatpak Bundle",
        "pkg" => "Installer Package",
        "zip" => "Compressed (zipped) Folder",
        "7z" => "7-Zip Archive",
        "rar" => "RAR Archive",
        "tar" => "Tape Archive",
        "gz" | "gzip" | "tgz" => "GZip Archive",
        "bz2" | "tbz" | "tbz2" => "BZip2 Archive",
        "xz" | "txz" => "XZ Archive",
        "zst" => "Zstandard Archive",
        "cab" => "Cabinet File",
        "iso" => "Disc Image File",
        "img" => "Disk Image File",
        "dmg" => "Apple Disk Image",
        "vhd" | "vhdx" => "Virtual Hard Disk",
        "vmdk" => "VMware Virtual Disk",
        "vdi" => "VirtualBox Disk Image",
        "qcow" | "qcow2" => "QEMU Disk Image",
        "jpg" | "jpeg" => "JPEG Image",
        "png" => "PNG Image",
        "gif" => "GIF Image",
        "bmp" => "Bitmap Image",
        "tif" | "tiff" => "TIFF Image",
        "webp" => "WebP Image",
        "heic" | "heif" => "HEIF Image",
        "svg" => "SVG Document",
        "ico" => "Icon",
        "icns" => "Apple Icon Image",
        "psd" => "Adobe Photoshop Image",
        "raw" | "cr2" | "nef" | "arw" | "dng" => "Camera Raw Image",
        "mp3" => "MP3 Audio File",
        "wav" => "Wave Sound",
        "flac" => "FLAC Audio File",
        "ogg" => "Ogg Audio File",
        "m4a" => "MPEG-4 Audio",
        "aac" => "AAC Audio File",
        "wma" => "Windows Media Audio File",
        "aiff" | "aif" => "AIFF Audio File",
        "opus" => "Opus Audio File",
        "mp4" | "m4v" => "MP4 Video",
        "mkv" => "Matroska Video",
        "avi" => "AVI Video",
        "mov" => "QuickTime Movie",
        "wmv" => "Windows Media Video",
        "webm" => "WebM Video",
        "mpg" | "mpeg" => "MPEG Video",
        "flv" => "Flash Video",
        "ttf" => "TrueType Font",
        "otf" => "OpenType Font",
        "woff" | "woff2" => "Web Font",
        "db" | "sqlite" | "sqlite3" => "Database File",
        "bak" => "Backup File",
        "tmp" | "temp" => "Temporary File",
        "cache" => "Cache File",
        "lock" => "Lock File",
        "pack" => "Git Pack File",
        "idx" => "Index File",
        "swp" => "Swap File",
        "vdf" => "Valve Data File",
        "pak" => "Game Data Package",
        "dat" => "Data File",
        "bin" => "Binary File",
        "rlib" => "Rust Library",
        "rmeta" => "Rust Metadata",
        "pyc" => "Compiled Python File",
        "wasm" => "WebAssembly Module",
        "torrent" => "Torrent File",
        "eml" => "E-mail Message",
        "pst" | "ost" => "Outlook Data File",
        "mdb" | "accdb" => "Microsoft Access Database",
        "pages" => "Pages Document",
        "numbers" => "Numbers Spreadsheet",
        "key" => "Keynote Presentation",
        _ => "",
    };
    if known.is_empty() {
        format!("{} File", ext.to_uppercase())
    } else {
        known.to_string()
    }
}
